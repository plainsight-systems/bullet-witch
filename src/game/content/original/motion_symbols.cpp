std::optional<std::uint32_t> original_motion_symbol(std::string_view name) {
  const auto found = std::ranges::lower_bound(symbols, name, {}, &Symbol::name);
  return found != symbols.end() && found->name == name
             ? std::optional<std::uint32_t>{found->slot}
             : std::nullopt;
}
