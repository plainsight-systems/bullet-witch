#ifndef BW_RENDERING_RHI_BACKENDS_METAL_METAL_MULTI_DRAW_HPP
#define BW_RENDERING_RHI_BACKENDS_METAL_METAL_MULTI_DRAW_HPP
// The Metal backend's counted multi-draw (command_list.hpp, Indirect work;
// rhi.md, Backends: Counted multi-draw): the encode kernel's pipeline, built
// from the library the Metal toolchain compiled at build time
// (multi_draw_encode.metal, embedded by CMake), and the indirect command
// buffers, execution range buffers and per-command argument buffer copies
// the kernel writes, pooled per frame in flight.
//
// Contract.
//   create builds the kernel's pipeline from the embedded library; it fails
//   with the step's text when the library, the function or the pipeline
//   cannot be made, and the backend fails creation with it.
//   acquire(maximum, frame) returns an indirect command buffer of at least
//   `maximum` render commands, a range buffer of one execution range per
//   kRangeCommands of them and a copies buffer of one top-level argument
//   buffer per command at kArgumentCopyStride, unused by any other
//   multi-draw of `frame` and by any frame the GPU may still be executing.
//   Each command inherits the render encoder's pipeline, sets its own
//   buffers at the converter's bind points 0 to 2 for both stages and holds
//   an indexed draw. The
//   pool of the frame's slot grows to the frame's largest number of
//   multi-draws and keeps each entry's capacity, so a steady frame creates
//   nothing (rhi.md, invariant 7: no API allocation per draw). An entry is
//   created with the next power of two at or above `maximum`. An empty
//   slot (null commands) means the device could not create one, and its
//   `refused` names the object the device refused.
//   reset(completed_frame) makes every slot whose last frame is at or below
//   completed_frame reusable.
//   Precondition of acquire: 1 <= maximum <= kMaxMultiDrawCount.
//
// Core guidelines read: R.1 (each Metal object has one owner that releases
// it), I.1 (the frame is an argument). Performance guidelines read: MEM.1 and
// MEM.4 (a per-frame pool rewound at one point), GPU.7 (a slot of a frame in
// flight is never rewritten).
#include "metal_api.hpp"

#include <cstddef>
#include <cstdint>
#include <memory>
#include <span>
#include <string>
#include <vector>

namespace bw::rhi::metal {

// The render commands one execution range covers: the largest length an
// execution range may hold on the Mac GPU family (rhi.md, Backends).
inline constexpr std::uint32_t kRangeCommands = 16384;
// Capabilities::max_multi_draw_count on this backend: sixteen execution
// ranges. It bounds a pooled indirect command buffer's size and the kernel's
// grid; a frame's largest list (a stage's clusters for every view) is below
// it.
inline constexpr std::uint32_t kMaxMultiDrawCount = 16U * kRangeCommands;
// The stride of the per-command copies of the 160-byte top-level argument
// buffer: the buffer offset alignment of this backend (metal_context.hpp,
// kBufferOffsetAlignment). multi_draw_encode.metal repeats it in words.
inline constexpr std::uint32_t kArgumentCopyStride = 256;

// The bytes of the encode kernel's library (generated by CMake from the
// metallib the Metal toolchain built; never committed).
[[nodiscard]] std::span<const unsigned char> multi_draw_encode_library() noexcept;

class MultiDrawPool {
public:
  struct Slot {
    MTL::IndirectCommandBuffer* commands{};
    MTL::Buffer* ranges{};
    MTL::Buffer* copies{};
    // In an empty slot, the object the device refused.
    const char* refused{};
  };

  // Returns the pool, or null with `error` set to the failing step.
  [[nodiscard]] static std::unique_ptr<MultiDrawPool>
  create(MTL::Device& device, std::uint32_t frames_in_flight, std::string& error);
  MultiDrawPool(const MultiDrawPool&) = delete;
  MultiDrawPool& operator=(const MultiDrawPool&) = delete;
  ~MultiDrawPool();

  [[nodiscard]] MTL::ComputePipelineState& pipeline() const noexcept { return *pipeline_; }
  [[nodiscard]] Slot acquire(std::uint32_t maximum, std::uint64_t frame);
  void reset(std::uint64_t completed_frame) noexcept;

private:
  struct Entry {
    MTL::IndirectCommandBuffer* commands{};
    MTL::Buffer* ranges{};
    MTL::Buffer* copies{};
    std::uint32_t capacity{};
    // In an empty entry, the object the device refused.
    const char* refused{};
  };
  struct FrameSlot {
    std::vector<Entry> entries;
    std::size_t used{};
    std::uint64_t last_frame{};
  };

  MultiDrawPool(MTL::Device& device, MTL::ComputePipelineState* pipeline,
                std::uint32_t frames_in_flight);
  [[nodiscard]] Entry create_entry(std::uint32_t maximum) const;

  MTL::Device* device_;
  MTL::ComputePipelineState* pipeline_;
  std::vector<FrameSlot> slots_;
};

} // namespace bw::rhi::metal
#endif
